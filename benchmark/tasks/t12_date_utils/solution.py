def is_leap(year):
    if year % 4 == 0:
        if year % 100 == 0:
            if year % 400 == 0:
                return True
            else:
                return False
        else:
            return True
    else:
        return False


def days_in_month(month, year):
    if month == 1:
        return 31
    elif month == 2:
        if is_leap(year):
            return 29
        else:
            return 28
    elif month == 3:
        return 31
    elif month == 4:
        return 30
